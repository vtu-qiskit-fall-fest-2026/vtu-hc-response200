"""Grounded language-model explanations for the GreenQ demo.

What the model does: turns GreenQ's saved results into short plain-English
sentences ("why this schedule", answers to questions, story captions) and turns
a typed job description into a job table.

What it never does: choose or change a schedule, or produce numbers. Every
schedule shown comes from brute force or QAOA; every number in a model
sentence is checked against the saved data and sentences with an unknown
number are dropped (``ground``).

It always degrades quietly, in this order:
  1. live call to an OpenAI-compatible endpoint (Groq by default), if a key is set
  2. results/llm_cache.json (pre-generated by scripts/build_llm_cache.py)
  3. fixed templates built from the same data
The API key is read from .env on the server only. It is never logged, returned
or sent to the browser.
"""

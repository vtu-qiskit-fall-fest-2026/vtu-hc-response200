# --------------------------------------------------------------------------- config

def config() -> dict | None:
    """Model settings, or None when the model must not be called (no key, or offline)."""
    load_dotenv(ROOT / ".env", override=False)
    if os.environ.get("GREENQ_LLM_OFFLINE") == "1":
        return None
    key = os.environ.get("GROQ_API_KEY") or os.environ.get("LLM_API_KEY")
    if not key:
        return None
    return {
        "key": key,
        "base": (os.environ.get("LLM_BASE_URL") or DEFAULT_BASE).rstrip("/"),
        "model": os.environ.get("LLM_MODEL") or DEFAULT_MODEL,
    }


def public_status() -> dict:
    """Safe to show anywhere: says whether a model is configured, never the key."""
    c = config()
    return {"configured": c is not None, "model": c["model"] if c else None, "cache": CACHE_FILE.exists()}


# --------------------------------------------------------------------------- facts

def _place(inst: dict, k: int) -> str:
    o = inst["options"][k]
    site = next(s for s in inst["sites"] if s["key"] == o["site"])["label"].split(" (")[0]
    return f"{site} {o['slot']}"


def _stop(data: dict, preset: str, w: float) -> tuple[dict, dict]:
    p = next((x for x in data["flex"]["presets"] if x["key"] == preset), data["flex"]["presets"][0])
    s = min(p["sweep"], key=lambda x: abs(x["w"] - w))
    return p, s


def _label(w: float) -> str:
    return {0.0: "water only", 0.5: "balanced", 1.0: "carbon only"}.get(round(w, 2), f"{round(w * 100)}% carbon, {round((1 - w) * 100)}% water")


def reasons(data: dict, a: int, b: int, before: list[int], after: list[int], j: int) -> list[str]:
    """Short reasons a job moved from option a to b (mirrors whyLines in web/src/lib/data.ts)."""
    inst = data["instance"]
    oa, ob = inst["options"][a], inst["options"][b]
    site = {s["key"]: s for s in inst["sites"]}
    slot = {s["key"]: s for s in inst["slots"]}
    out = []
    if slot[ob["slot"]]["carbon_kg_per_kwh"] < slot[oa["slot"]]["carbon_kg_per_kwh"]:
        out.append(f"cleaner {ob['slot']} grid")
    if site[ob["site"]]["wue"][ob["slot"]] < site[oa["site"]]["wue"][oa["slot"]]:
        out.append("air cooling saves water" if site[ob["site"]]["cooling"] == "air-cooled" else f"less cooling water at {ob['slot']}")
    if site[ob["site"]]["pue"] < site[oa["site"]]["pue"]:
        out.append("less cooling electricity")
    if before.count(a) > 1 and after.count(b) <= 1:
        out.append("leaves a crowded slot")
    if not out and ob["kg_co2_per_kwh"] > oa["kg_co2_per_kwh"] and ob["litres_per_kwh"] > oa["litres_per_kwh"]:
        out.append("makes room for a bigger job")
    return out or ["balances carbon and water"]


def moves(data: dict, preset: str, w: float) -> list[dict]:
    inst = data["instance"]
    _, s = _stop(data, preset, w)
    before, after = data["naive"]["schedule"], s["best"]["schedule"]
    out = []
    for j, job in enumerate(inst["jobs"]):
        if before[j] != after[j]:
            out.append({"job": job["label"], "from": _place(inst, before[j]), "to": _place(inst, after[j]),
                        "reasons": reasons(data, before[j], after[j], before, after, j)})
    return out



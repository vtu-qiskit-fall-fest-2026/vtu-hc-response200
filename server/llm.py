def facts_text(f: dict[str, str]) -> str:
    return "\n".join(f"- {k}: {v}" for k, v in f.items())


# --------------------------------------------------------------------------- grounding

_NUM = re.compile(r"(?<![\w.])[-−]?\d[\d,]*(?:\.\d+)?")


def numbers(text: str) -> list[float]:
    out = []
    for m in _NUM.findall(text):
        try:
            out.append(float(m.replace(",", "").replace("−", "-")))
        except ValueError:
            pass
    return out


def allowed_numbers(f: dict[str, str]) -> list[float]:
    vals = set()
    for v in f.values():
        for n in numbers(v):
            vals.update({n, abs(n)})
    vals.update(range(0, 11))  # small counts: "two sites", "4 jobs", "one layer"
    return sorted(vals)


def _ok(n: float, allowed: list[float]) -> bool:
    for a in allowed:
        if n == a or abs(n - a) <= 0.005 * max(abs(a), 1e-9):
            return True
        if float(n).is_integer() and round(a) == n:
            return True
        if round(a, 1) == n or round(a, 2) == n:
            return True
    return False


_BANNED = re.compile(r"\b(should|recommend|instead run|you could move)\b", re.I)


_PLACE = re.compile(r"(?:Site\s*)?\b([AB])\b[\s,]*(day|night)", re.I)
_STAYS = re.compile(r"did not move|didn't move|does not move|doesn't move|not moved|stays|stayed|remains|remained", re.I)
_MOVES = re.compile(r"\bmov(?:e|ed|es|ing)\b|→|->|shift", re.I)


def moves_consistent(sent: str, move_sets: list[list[dict]], job_labels: list[str]) -> bool:
    """A sentence that says a job moved (or stayed) must agree with at least one
    of the given move lists; a stated destination must be that job's real one."""
    for label in job_labels:
        names = {label.lower(), label.split()[0].lower()}
        if not any(re.search(rf"\b{re.escape(n)}\b", sent.lower()) for n in names):
            continue
        stays, moved = bool(_STAYS.search(sent)), bool(_MOVES.search(sent))
        if not (stays or moved):
            continue
        places = {(a.upper(), b.lower()) for a, b in _PLACE.findall(sent)}
        ok = False
        for mv in move_sets:
            m = next((x for x in mv if x["job"] == label), None)
            if stays and m is None:
                ok = True
            elif moved and not stays and m is not None:
                site, slot = m["to"].split(" ")[-2], m["to"].split(" ")[-1]
                ok = not places or (site, slot) in places
            if ok:
                break
        if not ok:
            return False
    return True


def ground(text: str, allowed: list[float], move_sets: list[list[dict]] | None = None, job_labels: list[str] | None = None) -> str:
    """Keep only sentences whose numbers all match the data, whose claims about
    moved jobs match the schedule (when move_sets is given), and that make no
    schedule suggestions or advantage claims."""
    keep = []
    for sent in re.split(r"(?<=[.!?])\s+", text.strip()):
        if not sent:
            continue
        if move_sets is not None and not moves_consistent(sent, move_sets, job_labels or []):
            continue
        if not all(_ok(n, allowed) for n in numbers(sent)):
            continue
        if _BANNED.search(sent):
            continue
        if re.search(r"advantage", sent, re.I) and not re.search(r"\b(no|not|n't|never|without)\b", sent, re.I):
            continue
        keep.append(sent)
    return " ".join(keep).strip()


# --------------------------------------------------------------------------- model call

_GATE = {"last": 0.0, "cool_until": 0.0}  # simple client-side rate limiting


def _chat(cfg: dict, system: str, user: str, schema: dict | None = None, timeout: float = 8.0, interactive: bool = True) -> str | None:
    """One chat completion. Interactive calls never wait: during a rate-limit
    cooldown, or within 1.2 s of the previous call, they return None at once so
    the caller falls back to the cache or a template. Batch calls (the cache
    builder) wait and retry on HTTP 429."""
    body: dict[str, Any] = {
        "model": cfg["model"],
        "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
        "temperature": 0.2,
        "max_completion_tokens": 900,
    }
    if "gpt-oss" in cfg["model"]:
        body["reasoning_effort"] = "low"
    if schema is not None:
        strict = "gpt-oss" in cfg["model"]
        body["response_format"] = ({"type": "json_schema", "json_schema": {"name": schema["name"], "strict": True, "schema": schema["schema"]}}
                                   if strict else {"type": "json_object"})
    for attempt in range(1 if interactive else 5):
        now = time.monotonic()
        if interactive and (now < _GATE["cool_until"] or now - _GATE["last"] < 1.2):
            return None
        _GATE["last"] = now
        try:
            r = httpx.post(f"{cfg['base']}/chat/completions", json=body, timeout=timeout,
                           headers={"Authorization": f"Bearer {cfg['key']}"})
        except httpx.HTTPError as e:
            print(f"[llm] call failed: {type(e).__name__}", flush=True)  # never the key
            return None
        if r.status_code == 429:
            try:
                wait = float(r.headers.get("retry-after", "10"))
            except ValueError:
                wait = 10.0
            _GATE["cool_until"] = time.monotonic() + wait
            print(f"[llm] rate limited, cooling down {wait:.0f} s", flush=True)
            if not interactive:
                time.sleep(wait + 0.5)
            continue
        if r.status_code != 200:
            print(f"[llm] call failed: HTTP {r.status_code}", flush=True)
            return None
        try:
            return r.json()["choices"][0]["message"]["content"]
        except (KeyError, IndexError, ValueError):
            return None
    return None


def _json(text: str | None) -> dict | None:
    if not text:
        return None
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        m = re.search(r"\{.*\}", text, re.S)
        try:
            return json.loads(m.group(0)) if m else None
        except json.JSONDecodeError:
            return None


RULES = ("You explain results from GreenQ, a demo that schedules data-centre jobs across two sites and two time slots "
         "to cut CO2 and water. Use ONLY the facts given. Do not invent or compute new numbers: copy numbers exactly as "
         "written in the facts, or use none. Never suggest a different schedule. Never claim quantum advantage. "
         "If the facts don't answer the question, say \"I don't know from GreenQ's saved results.\" "
         "Never relate, compare or combine two numbers unless a fact states that relation. Don't call a percentage a 'success rate'. "
         "Plain words for a non-expert, short sentences.")


# --------------------------------------------------------------------------- cache

def load_cache() -> dict:
    try:
        return json.loads(CACHE_FILE.read_text())
    except (OSError, json.JSONDecodeError):
        return {}


def _key(preset: str, w: float) -> str:
    return f"{preset}:{round(w, 2)}"


_LIVE: dict[str, Any] = {}  # in-process memo of live answers


# --------------------------------------------------------------------------- explain

EXPLAIN_SCHEMA = {"name": "explanation", "schema": {
    "type": "object", "additionalProperties": False, "required": ["lines"],
    "properties": {"lines": {"type": "array", "items": {"type": "string"}}}}}


def template_explain(data: dict, preset: str, w: float) -> list[str]:
    return [f"{m['job']} → {m['to']}: {', '.join(m['reasons'][:2])}." for m in moves(data, preset, w)]


def generate_explain(cfg: dict, data: dict, preset: str, w: float, interactive: bool = True) -> list[str] | None:
    f = facts(data, preset, w)
    mv = moves(data, preset, w)
    if not mv:
        return []
    user = (f"Facts:\n{facts_text(f)}\n\nFor each moved job write one line (at most 14 words) saying where it went and why, "
            f"using the reasons in 'moved jobs'. Return JSON {{\"lines\": [...]}} with {len(mv)} lines.")
    out = _json(_chat(cfg, RULES, user, EXPLAIN_SCHEMA, interactive=interactive))
    if not out or not isinstance(out.get("lines"), list):
        return None
    allowed = allowed_numbers(f)
    labels = [j["label"] for j in data["instance"]["jobs"]]
    lines = [ground(str(x), allowed, [mv], labels) for x in out["lines"][:3]]
    lines = [x for x in lines if x]
    return lines or None


def explain(data: dict, preset: str, w: float) -> dict:
    key = _key(preset, w)
    cached = load_cache().get("explain", {}).get(key)
    if cached:
        allowed = allowed_numbers(facts(data, preset, w))
        labels = [j["label"] for j in data["instance"]["jobs"]]
        lines = [x for x in (ground(t, allowed, [moves(data, preset, w)], labels) for t in cached["lines"]) if x]
        if lines or not moves(data, preset, w):
            return {"lines": lines, "source": "cached"}
    cfg = config()
    if cfg:
        memo = _LIVE.get(f"explain:{key}")
        if memo is None:
            memo = generate_explain(cfg, data, preset, w)
            if memo is not None:
                _LIVE[f"explain:{key}"] = memo
        if memo is not None:
            return {"lines": memo, "source": "live"}
    return {"lines": template_explain(data, preset, w), "source": "template"}


# --------------------------------------------------------------------------- ask

ASK_SCHEMA = {"name": "answer", "schema": {
    "type": "object", "additionalProperties": False, "required": ["answer", "focus"],
    "properties": {"answer": {"type": "string"},
                   "focus": {"type": "string", "enum": [*FOCUS.keys(), "none"]}}}}


def _norm(q: str) -> str:
    return re.sub(r"[^a-z ]", "", q.lower()).strip()


def template_answer(data: dict, preset: str, w: float, question: str) -> dict | None:
    """Hand-written answers for the five example questions, filled from the data."""
    f = facts(data, preset, w)
    q = _norm(question)
    inst = data["instance"]
    if q == _norm(EXAMPLES[0]):
        m = next((x for x in moves(data, preset, w) if x["job"].startswith("Video")), None)
        if m:
            text = f"Video rendering moved from {m['from']} to {m['to']}: {', '.join(m['reasons'][:2])}."
        else:
            j = next(i for i, x in enumerate(inst["jobs"]) if x["label"].startswith("Video"))
            text = f"At this setting video rendering stays at {_place(inst, data['naive']['schedule'][j])}: moving it wouldn't lower the total."
        return {"text": text, "focus": "schedule"}
    if q == _norm(EXAMPLES[1]):
        _, e = _stop(data, preset, 0.0)
        air = sum(1 for k in e["best"]["schedule"] if inst["options"][k]["site"] == "air")
        return {"text": f"With water only, GreenQ {f['if water only']}. {air} of {len(inst['jobs'])} jobs then run at the air-cooled site, which uses almost no water on site.", "focus": "tradeoff"}
    if q == _norm(EXAMPLES[2]):
        return {"text": f"It ran on real IBM hardware: {f['real IBM hardware']}. Shots in the best tenth: {f['shots in the best tenth of schedules']}.", "focus": "histogram"}
    if q == _norm(EXAMPLES[3]):
        return {"text": f"No. A laptop checks {f['schedules checked by laptop']} schedules almost instantly and grades the quantum answer. No quantum advantage is claimed at this size.", "focus": "methods"}
    if q == _norm(DEMO_QUESTIONS[0]):
        _, s = _stop(data, preset, w)
        return {"text": (f"GreenQ decides where and when flexible data-centre jobs run, to cut carbon and water together. "
                         f"In our example it saves {s['saved_kg_co2']:,.0f} kg CO2 and {s['saved_litres']:,.0f} L of water versus run now. "
                         f"A quantum algorithm (QAOA) ran on a real IBM computer, and a laptop checks every answer."), "focus": "schedule"}
    if q == _norm(DEMO_QUESTIONS[1]):
        return {"text": (f"No, not at this size. A laptop checks {f['schedules checked by laptop']} schedules faster than the quantum computer. "
                         "We built GreenQ to show a correct quantum formulation, tested on real hardware, as a step toward bigger problems."), "focus": "methods"}
    if q == _norm(EXAMPLES[4]):
        lim = f.get("scaling (simulated)", "bigger problems need many more gates")
        return {"text": f"Four illustrative jobs on two sites, so a laptop wins easily. Noise grows with size: {lim}.", "focus": "scaling"}
    return None


def generate_answer(cfg: dict, data: dict, preset: str, w: float, question: str, interactive: bool = True) -> dict | None:
    f = facts(data, preset, w)
    user = (f"Facts:\n{facts_text(f)}\n\nQuestion: {question}\n\nAnswer in at most 3 short sentences (at most 60 words). "
            f"Pick focus = the screen widget that shows the answer ({', '.join(FOCUS)}), or none. Return JSON.")
    out = _json(_chat(cfg, RULES, user, ASK_SCHEMA, timeout=10.0, interactive=interactive))
    if not out or not isinstance(out.get("answer"), str):
        return None
    labels = [j["label"] for j in data["instance"]["jobs"]]
    sets = [moves(data, preset, w), moves(data, preset, 0.0), moves(data, preset, 1.0)]
    text = ground(out["answer"], allowed_numbers(f), sets, labels)
    if not text:
        return None
    focus = out.get("focus") if out.get("focus") in FOCUS else None
    return {"text": text, "focus": focus}


def ask(data: dict, preset: str, w: float, question: str, demo: bool = False) -> dict:
    question = question.strip()[:300]
    key = f"{_key(preset, w)}|{_norm(question)}"

    def reply(r: dict, source: str) -> dict:
        focus = r.get("focus")
        return {"text": r["text"], "source": source, "focus": focus, "screen": FOCUS.get(focus) if focus else None}

    cached = load_cache().get("ask", {}).get(key)
    if cached:
        text = ground(cached["text"], allowed_numbers(facts(data, preset, w)))
        if text:
            return reply({"text": text, "focus": cached.get("focus")}, "cached")
    example = _norm(question) in {_norm(q) for q in EXAMPLES + DEMO_QUESTIONS}
    cfg = config()
    if cfg and not example and not demo:  # example questions: reviewed cache or hand-written template only
        memo = _LIVE.get(f"ask:{key}") or generate_answer(cfg, data, preset, w, question)
        if memo:
            _LIVE[f"ask:{key}"] = memo
            return reply(memo, "live")
    t = template_answer(data, preset, w, question)
    if t:
        return reply(t, "template")
    return {"text": "Offline, I can answer the five example questions. Pick one of them above.", "source": "template", "focus": None, "screen": None}


# --------------------------------------------------------------------------- parse jobs

JOBS_SCHEMA = {"name": "jobs", "schema": {
    "type": "object", "additionalProperties": False, "required": ["jobs"],
    "properties": {"jobs": {"type": "array", "items": {
        "type": "object", "additionalProperties": False,
        "required": ["name", "kwh", "home_site", "submitted_slot", "deadline", "residency"],
        "properties": {
            "name": {"type": "string"},
            "kwh": {"type": "number"},
            "home_site": {"type": "string", "enum": ["evap", "air"]},
            "submitted_slot": {"type": "string", "enum": ["day", "night"]},
            "deadline": {"type": "boolean"},
            "residency": {"type": "boolean"}}}}}}}

PARSE_RULES = ("Extract data-centre jobs from the user's text into JSON. Site A = \"evap\", Site B = \"air\" (default evap). "
               "submitted_slot is when the job arrives: \"night\" if the text says night/nightly/overnight, else \"day\". "
               "deadline = true only if it must finish by the end of the day. residency = true only if its data must stay at "
               "its home site. kwh must be a number written in the text; never invent one. Short names (max 40 characters). "
               "At most 5 jobs.")


def _rule_parse(text: str) -> list[dict]:
    """No-model fallback: one job per sentence that states a kWh figure."""
    jobs = []
    for sent in re.split(r"(?<=[.;!?])\s+|\n+", text):
        m = re.search(r"(\d[\d,]*(?:\.\d+)?)\s*kwh", sent, re.I)
        if not m:
            continue
        low = sent.lower()
        words = re.sub(r"\d[\d,]*(?:\.\d+)?\s*kwh|site [ab]|\b(a|an|the|of|at|on|in|to|by|must|it|can|run|any|time|that|there|stay|due|end|day|night|nightly)\b", " ", low)
        name = " ".join(words.split()[:4]).strip(" ,.") or f"Job {len(jobs) + 1}"
        night = bool(re.search(r"night|overnight", low))
        deadline = bool(re.search(r"end of (the )?day|deadline|due by|by evening", low)) and not night
        jobs.append({"name": name[:40].capitalize(), "kwh": float(m.group(1).replace(",", "")),
                     "home_site": "air" if re.search(r"site b|air", low) else "evap",
                     "submitted_slot": "night" if night else "day",
                     "deadline": deadline,
                     "residency": bool(re.search(r"stay|local|residen|must remain|can't leave|cannot leave", low))})
    return jobs[:5]


def parse_jobs(text: str, validate, demo: bool = False) -> dict:
    """text -> {"jobs": [...] | None, "note": str, "source": ...}. ``validate`` is the
    server's pydantic job check; anything that fails it is dropped and reported."""
    text = text.strip()[:800]
    stated = numbers(text)
    raw, source = None, "template"
    cfg = None if demo else config()  # the demo uses the rule reader: deterministic, offline
    if cfg:
        out = _json(_chat(cfg, PARSE_RULES, text, JOBS_SCHEMA, timeout=12.0))
        if out and isinstance(out.get("jobs"), list):
            raw, source = out["jobs"], "live"
    if raw is None:
        raw = _rule_parse(text)
    jobs, dropped = [], []
    for j in raw[:5]:
        try:
            if not any(abs(float(j.get("kwh", -1)) - n) < 1e-6 for n in stated):
                raise ValueError("kWh not in the text")
            if j.get("deadline") and j.get("submitted_slot") == "night":
                j = {**j, "deadline": False}
            jobs.append(validate(j))
        except Exception:  # noqa: BLE001 - any invalid job is dropped and reported
            dropped.append(str(j.get("name", "a job"))[:40])
    if not jobs:
        return {"jobs": None, "note": "Couldn't find jobs with a kWh figure (50–5,000 kWh) in that text, so here is the form instead.", "source": source}
    note = f"Skipped: {', '.join(dropped)} (needs a kWh figure between 50 and 5,000)." if dropped else ""
    return {"jobs": jobs, "note": note, "source": source}


# --------------------------------------------------------------------------- narration

NARRATION_SCHEMA = {"name": "captions", "schema": {
    "type": "object", "additionalProperties": False, "required": CAPTIONS,
    "properties": {c: {"type": "string"} for c in CAPTIONS}}}


def narration() -> dict:
    lines = load_cache().get("narration", {})
    return {"lines": lines, "source": "cached" if lines else "none"}


def generate_narration(cfg: dict, data: dict) -> dict | None:
    f = facts(data, "flexible", 0.5)
    user = (f"Facts:\n{facts_text(f)}\n\nWrite one spoken caption (at most 18 words) for each moment of a 50-second demo: "
            "start (the idea: same jobs, where and when), run_now (every job at home when it arrives; Site A crowded at night), "
            "run_smart (jobs move; footprint drops), tradeoff (slider: carbon vs water compromise), circuit (8 qubits, a where and a when "
            "per job), histogram (real IBM shots vs random guessing), compare (classical methods find the same answer, faster; shown on "
            "purpose), ask (an AI explains saved results and never picks the schedule), about (cited or labelled; no quantum advantage). Return JSON.")
    out = _json(_chat(cfg, RULES, user, NARRATION_SCHEMA, timeout=20.0, interactive=False))
    if not out:
        return None
    allowed = allowed_numbers(f)
    res = {c: ground(str(out.get(c, "")), allowed) for c in CAPTIONS}
    return {c: v for c, v in res.items() if v}


def build_demo_answers(data: dict, cache: dict, pause: float = 2.2) -> dict:
    """Add (or refresh) the cached answers to the demo's questions, at the demo's setting."""
    cfg = config()
    if cfg is None:
        raise RuntimeError("No GROQ_API_KEY in .env (or GREENQ_LLM_OFFLINE=1); nothing to generate.")
    cache.setdefault("ask", {})
    for q in DEMO_QUESTIONS:
        # the honest question must also say why we built it; the instruction is part of the prompt only
        prompt = q + (" Answer honestly, then say why we still built it." if q == DEMO_QUESTIONS[1] else "")
        a = generate_answer(cfg, data, "flexible", 0.5, prompt, interactive=False)
        if a:
            cache["ask"][f"{_key('flexible', 0.5)}|{_norm(q)}"] = a
        time.sleep(pause)
    return cache


def build_cache(data: dict, presets=("flexible", "mixed", "rigid"), weights=(0.0, 0.5, 1.0), pause: float = 2.2) -> dict:
    """Pre-generate everything the demo shows from the model. Needs a key."""
    cfg = config()
    if cfg is None:
        raise RuntimeError("No GROQ_API_KEY in .env (or GREENQ_LLM_OFFLINE=1); nothing to generate.")
    cache: dict[str, Any] = {"model": cfg["model"], "generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                             "note": "Generated by scripts/build_llm_cache.py; every number checked against results/ui_data.json.",
                             "explain": {}, "ask": {}, "narration": {}}
    for p in presets:
        for w in weights:
            lines = generate_explain(cfg, data, p, w, interactive=False)
            if lines is not None:
                cache["explain"][_key(p, w)] = {"lines": lines}
            time.sleep(pause)
            for q in EXAMPLES:
                a = generate_answer(cfg, data, p, w, q, interactive=False)
                if a:
                    cache["ask"][f"{_key(p, w)}|{_norm(q)}"] = a
                time.sleep(pause)
    # Story captions stay hand-written (web/src/lib/story.ts): generated ones were
    # less accurate in review. generate_narration() is kept for experiments.
    return cache
